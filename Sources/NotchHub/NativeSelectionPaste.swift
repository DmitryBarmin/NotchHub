import AppKit
import Carbon

/// Thread-safe lazy data provider: AppKit may request a representation outside
/// the main actor while the initiating transaction remains suspended.
private final class NativePasteData: NSObject, NSPasteboardItemDataProvider {
    private let data: Data
    private let lock = NSLock()
    private var consumed = false
    init(_ text: String) { data = Data(text.utf8) }
    var wasRead: Bool { lock.lock(); defer { lock.unlock() }; return consumed }
    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        guard type == .string, item.setData(data, forType: type) else { return }
        lock.lock(); consumed = true; lock.unlock()
    }
}

/// One explicit copy → local correction → paste transaction. No AX text APIs,
/// activation, Unicode typing, Return, clipboard history, or network are involved.
@MainActor enum NativeSelectionPaste {
    static func perform(processIdentifier: pid_t, validate: @escaping () throws -> Void,
                        correct: @escaping (String) async throws -> LocalSpellingOutcome,
                        didRestore: @escaping (Int) -> Void = { _ in }) async throws -> LocalSpellingOutcome {
        let transaction = Transaction()
        defer { withExtendedLifetime(transaction) {} }
        return try await transaction.perform(processIdentifier: processIdentifier, validate: validate, correct: correct, didRestore: didRestore)
    }

    struct InputCounters: Equatable {
        var keyDown: UInt32 = 0
        var leftMouseDown: UInt32 = 0
        var rightMouseDown: UInt32 = 0
        var otherMouseDown: UInt32 = 0
        var scrollWheel: UInt32 = 0
        static func physical() -> Self {
            InputCounters(keyDown: CGEventSource.counterForEventType(.hidSystemState, eventType: .keyDown),
                          leftMouseDown: CGEventSource.counterForEventType(.hidSystemState, eventType: .leftMouseDown),
                          rightMouseDown: CGEventSource.counterForEventType(.hidSystemState, eventType: .rightMouseDown),
                          otherMouseDown: CGEventSource.counterForEventType(.hidSystemState, eventType: .otherMouseDown),
                          scrollWheel: CGEventSource.counterForEventType(.hidSystemState, eventType: .scrollWheel))
        }
    }

    @MainActor final class Transaction {
        static let marker = NSPasteboard.PasteboardType("local.notchhub.native-selection-transaction")
        static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
        static let generated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
        // Retry may snapshot only payloads this process intentionally left for a
        // queued paste. Unknown markers and all Concealed data remain protected.
        private static var staleMarkers: [Data] = []
        private let pasteboard: NSPasteboard
        private let postKey: @MainActor (pid_t, CGKeyCode) throws -> Void
        private let modifiers: () -> CGEventFlags
        private let inputs: () -> InputCounters
        private let now: () -> TimeInterval
        private let pause: (TimeInterval) async throws -> Void
        private let settle: (TimeInterval) async -> Void
        private let maximumBytes: Int
        private let notifications: NotificationCenter
        private var terminationSnapshot: Snapshot?
        private var terminationRestored: ((Int) -> Void)?
        private var activePasteProvider: NativePasteData?
        private var activePasteData: Data?
        private var pastePosted = false
        private var ownedCount: Int?
        private var settlementDeadline: TimeInterval = 0
        private let markerData = Data(UUID().uuidString.utf8)

        init(pasteboard: NSPasteboard = .general,
             postKey: @escaping @MainActor (pid_t, CGKeyCode) throws -> Void = NativeSelectionPaste.postKey,
             modifiers: @escaping () -> CGEventFlags = { CGEventSource.flagsState(.hidSystemState) },
             inputs: @escaping () -> InputCounters = InputCounters.physical,
             now: @escaping () -> TimeInterval = { ProcessInfo.processInfo.systemUptime },
             pause: @escaping (TimeInterval) async throws -> Void = { try await Task.sleep(nanoseconds: UInt64($0 * 1_000_000_000)) },
             settle: @escaping (TimeInterval) async -> Void = { delay in
                 // Cleanup must finish even after the operation's Task was cancelled.
                 await Task.detached { try? await Task.sleep(nanoseconds: UInt64(delay * 1_000_000_000)) }.value
             }, maximumBytes: Int = HubStore.maxBytes, notifications: NotificationCenter = .default) {
            self.pasteboard = pasteboard; self.postKey = postKey; self.modifiers = modifiers; self.inputs = inputs
            self.now = now; self.pause = pause; self.settle = settle; self.maximumBytes = maximumBytes; self.notifications = notifications
        }

        private struct Snapshot {
            let count: Int
            let items: [NSPasteboardItem]
        }
        private static let heldModifiers: CGEventFlags = [.maskCommand, .maskShift, .maskControl, .maskAlternate]
        private func failure(_ message: String) -> TextCorrectionFailure { TextCorrectionFailure(message) }
        private static func isProtected(_ pasteboard: NSPasteboard) -> Bool {
            let types = Set((pasteboard.types ?? []) + (pasteboard.pasteboardItems ?? []).flatMap(\.types))
            if types.contains(NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")) { return true }
            guard types.contains(transient) || types.contains(generated) else { return false }
            guard types.contains(marker), let value = pasteboard.data(forType: marker), staleMarkers.contains(value) else { return true }
            return false
        }
        private func snapshot() throws -> Snapshot {
            let count = pasteboard.changeCount
            guard !Self.isProtected(pasteboard) else { throw failure("Защищённый буфер не читается и не заменяется") }
            let original = pasteboard.pasteboardItems ?? []
            guard original.count <= 256 else { throw failure("В буфере слишком много элементов — вставка отменена") }
            // Items expose the canonical representations. The board also advertises
            // legacy aliases (e.g. NSStringPboardType), recreated by AppKit on restore.
            var bytes = 0, items: [NSPasteboardItem] = []
            for originalItem in original {
                guard originalItem.types.count <= 256 else { throw failure("В буфере слишком много форматов — вставка отменена") }
                let item = NSPasteboardItem()
                for type in originalItem.types {
                    guard pasteboard.changeCount == count, !Self.isProtected(pasteboard) else { throw failure("Буфер изменился — повтори сочетание") }
                    guard let data = originalItem.data(forType: type), data.count <= maximumBytes - bytes else {
                        throw failure("Не удалось сохранить буфер целиком в пределах 30 МБ — вставка отменена")
                    }
                    bytes += data.count
                    guard item.setData(data, forType: type) else { throw failure("Не удалось сохранить один из форматов буфера") }
                }
                items.append(item)
            }
            guard pasteboard.changeCount == count, !Self.isProtected(pasteboard) else { throw failure("Буфер изменился — повтори сочетание") }
            return Snapshot(count: count, items: items)
        }
        private func waitForModifiers() async throws {
            let deadline = now() + 2
            while !modifiers().intersection(Self.heldModifiers).isEmpty {
                try Task.checkCancellation()
                guard now() < deadline else { throw failure("Отпусти ⌘, ⇧, ⌃ и ⌥ и повтори сочетание") }
                try await pause(0.02)
            }
            try Task.checkCancellation()
        }
        private func checkInput(_ baseline: InputCounters) throws {
            try Task.checkCancellation()
            guard inputs() == baseline else { throw failure("Во время исправления изменился ввод — вставка отменена") }
        }
        private func claim(_ text: String?, expectedCount: Int) throws -> NativePasteData? {
            let item = NSPasteboardItem()
            let provider = text.map(NativePasteData.init)
            if let provider { guard item.setDataProvider(provider, forTypes: [.string]) else { throw failure("Не удалось подготовить исправление") } }
            guard item.setData(Data(), forType: Self.transient), item.setData(Data(), forType: Self.generated),
                  item.setData(markerData, forType: Self.marker) else { throw failure("Не удалось подготовить временный буфер") }
            guard pasteboard.changeCount == expectedCount else { throw failure("Буфер изменился — вставка отменена") }
            let cleared = pasteboard.clearContents()
            ownedCount = cleared
            guard pasteboard.changeCount == cleared else { throw failure("Буфер изменился — вставка отменена") }
            guard pasteboard.writeObjects([item]) else { throw failure("Не удалось записать временный буфер") }
            let written = pasteboard.changeCount
            guard pasteboard.data(forType: Self.marker) == markerData, pasteboard.changeCount == written else {
                throw failure("Буфер изменился — вставка отменена")
            }
            ownedCount = written
            return provider
        }
        private func restore(_ snapshot: Snapshot, didRestore: (Int) -> Void) throws {
            guard let ownedCount, pasteboard.changeCount == ownedCount else { self.ownedCount = nil; return }
            let cleared = pasteboard.clearContents()
            self.ownedCount = cleared
            guard pasteboard.changeCount == cleared else { self.ownedCount = nil; return }
            if !snapshot.items.isEmpty {
                guard pasteboard.writeObjects(snapshot.items) else { throw failure("Не удалось восстановить исходный буфер") }
            }
            let restored = pasteboard.changeCount
            self.ownedCount = nil
            didRestore(restored)
        }

        /// Never expose an unrelated old clipboard to an already queued CmdV.
        /// An unread paste stays available, with transient markers, even on timeout/quit.
        private func preserveUnreadPaste() -> Bool {
            guard pastePosted, activePasteProvider?.wasRead != true,
                  let ownedCount, pasteboard.changeCount == ownedCount, let activePasteData else { return false }
            _ = pasteboard.setData(activePasteData, forType: .string)
            if !Self.staleMarkers.contains(markerData) {
                Self.staleMarkers.append(markerData)
                if Self.staleMarkers.count > 16 { Self.staleMarkers.removeFirst() }
            }
            self.ownedCount = nil
            return true
        }
        private func restoreForTermination() {
            if preserveUnreadPaste() { return }
            guard let snapshot = terminationSnapshot, let callback = terminationRestored else { return }
            try? restore(snapshot, didRestore: callback)
        }

        func perform(processIdentifier: pid_t, validate: @escaping () throws -> Void,
                     correct: @escaping (String) async throws -> LocalSpellingOutcome,
                     didRestore: @escaping (Int) -> Void = { _ in }) async throws -> LocalSpellingOutcome {
            guard processIdentifier > 0 else { throw failure("Исходное приложение недоступно") }
            try Task.checkCancellation()
            try await waitForModifiers()
            try validate()
            let original = try snapshot()
            let baseline = inputs()
            terminationSnapshot = original; terminationRestored = didRestore
            let termination = notifications.addObserver(forName: NSApplication.willTerminateNotification, object: nil, queue: .main) { [weak self] _ in
                MainActor.assumeIsolated { self?.restoreForTermination() }
            }
            defer {
                notifications.removeObserver(termination); terminationSnapshot = nil; terminationRestored = nil
                activePasteProvider = nil; activePasteData = nil; pastePosted = false
            }
            var pendingPaste: NativePasteData?
            var pasteDeadline: TimeInterval = 0
            let result: Result<LocalSpellingOutcome, Error>
            do {
                _ = try claim(nil, expectedCount: original.count)
                try checkInput(baseline)
                try validate()
                let copyDeadline = now() + 1
                settlementDeadline = copyDeadline
                try postKey(processIdentifier, CGKeyCode(kVK_ANSI_C))
                var copiedText: String?
                var copyPublicationStarted = false
                while now() < copyDeadline {
                    try checkInput(baseline)
                    try validate()
                    if let ownedCount, pasteboard.changeCount != ownedCount {
                        // Copy can clear ownership first and publish its types/data on
                        // a later run-loop turn. Track that empty intermediate board.
                        self.ownedCount = pasteboard.changeCount
                        copyPublicationStarted = true
                    }
                    if copyPublicationStarted, let copiedCount = ownedCount {
                        guard !Self.isProtected(pasteboard) else { throw failure("Приложение скопировало защищённый текст — исправление отменено") }
                        if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
                            try TextCorrectionLimits.validate(text)
                            guard pasteboard.changeCount == copiedCount else { self.ownedCount = nil; throw failure("Буфер изменился — вставка отменена") }
                            try checkInput(baseline)
                            settlementDeadline = 0
                            copiedText = text
                            break
                        }
                    }
                    try await pause(0.02)
                }
                guard let text = copiedText else { throw failure("Не удалось скопировать выделение. Выдели текст в редактируемом поле и повтори") }
                let outcome = try await correct(text)
                try checkInput(baseline)
                try validate()
                guard let copiedCount = ownedCount, pasteboard.changeCount == copiedCount else {
                    ownedCount = nil; throw failure("Буфер изменился — исправление не вставлено")
                }
                if outcome.correctedCount > 0, outcome.text != text {
                    guard !outcome.text.isEmpty, outcome.text.utf8.count <= TextCorrectionLimits.maxResultBytes else {
                        throw failure("Результат исправления пустой или слишком большой")
                    }
                    try await waitForModifiers()
                    try checkInput(baseline)
                    try validate()
                    pendingPaste = try claim(outcome.text, expectedCount: copiedCount)
                    activePasteProvider = pendingPaste; activePasteData = Data(outcome.text.utf8)
                    try checkInput(baseline)
                    try validate()
                    pasteDeadline = now() + 1
                    try postKey(processIdentifier, CGKeyCode(kVK_ANSI_V))
                    pastePosted = true
                    while pendingPaste?.wasRead != true {
                        try Task.checkCancellation()
                        guard now() < pasteDeadline else { throw failure("Приложение не подтвердило чтение вставки — исправление не подтверждено") }
                        try await pause(0.02)
                    }
                }
                result = .success(outcome)
            } catch { result = .failure(error) }
            // Even cancelled Tasks keep the temporary representation alive until a
            // consumer reads it or the bounded deadline expires. Never retry insertion.
            if let pendingPaste {
                while !pendingPaste.wasRead, now() < pasteDeadline { await settle(min(0.02, pasteDeadline - now())) }
                if pendingPaste.wasRead { await settle(0.1) }
            } else {
                let delay = max(0, settlementDeadline - now())
                if delay > 0 { await settle(delay) }
            }
            if pastePosted, pendingPaste?.wasRead != true {
                let preserved = preserveUnreadPaste()
                throw failure(preserved
                    ? "Вставка не подтверждена; исправление оставлено в буфере. Вставь его через ⌘V."
                    : "Вставка не подтверждена. Буфер изменился — новые данные не заменены.")
            }
            try restore(original, didRestore: didRestore)
            return try result.get()
        }
    }

    private static func postKey(_ processIdentifier: pid_t, _ keyCode: CGKeyCode) throws {
        guard CGPreflightPostEventAccess() else {
            throw TextCorrectionFailure("Разреши NotchHub Универсальный доступ в настройках macOS и повтори сочетание")
        }
        guard let source = CGEventSource(stateID: .privateState),
              let down = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: true),
              let up = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: false) else {
            throw TextCorrectionFailure("Не удалось подготовить системное сочетание клавиш")
        }
        down.flags = .maskCommand; up.flags = .maskCommand
        down.postToPid(processIdentifier); up.postToPid(processIdentifier)
    }
}

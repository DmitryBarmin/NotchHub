import XCTest
import AppKit
import SwiftUI
@testable import NotchHub

final class FormattingInputTests: XCTestCase {
    func testCurrentClipboardWinsWithoutReadingExternalSelection() {
        var reads = 0
        let result = FormattingInput.resolve(external: { reads += 1; return FormattingInput(text: "selected", externalSelection: nil, notice: "readonly selection") }, clipboard: { "copied" })
        XCTAssertEqual(result.text, "copied")
        XCTAssertNil(result.externalSelection)
        XCTAssertEqual(reads, 0)
    }
    func testSelectedTextIsUsedWhenClipboardHasNoText() {
        let result = FormattingInput.resolve(external: { FormattingInput(text: "selected", externalSelection: nil, notice: "readonly selection") }, clipboard: { throw ClipActionFailure("В буфере нет текста") })
        XCTAssertEqual(result.text, "selected")
    }
    func testClipboardFallbackIsClearlyCopyOnlyAndDoesNotUseHistory() {
        let result = FormattingInput.resolve(external: { throw ClipActionFailure("unavailable") }, clipboard: { "current clipboard" })
        XCTAssertEqual(result.text, "current clipboard")
        XCTAssertNil(result.externalSelection)
        XCTAssertEqual(result.notice, "Текст из буфера — результат можно скопировать")
    }
    func testUnavailableAndEmptyClipboardReturnsVisibleInstructions() {
        let result = FormattingInput.resolve(external: { throw ClipActionFailure("Нет выделения") }, clipboard: { throw ClipActionFailure("Скопируй текст и нажми «Из буфера»") })
        XCTAssertEqual(result.text, "")
        XCTAssertTrue(result.notice.contains("Из буфера"))
        XCTAssertTrue(result.notice.contains("Нет выделения"))
    }
    @MainActor func testHostedEditorUpdatesFromEmptyToImportedClipboard() async throws {
        _ = NSApplication.shared
        var text = ""
        var range = NSRange(location: 0, length: 0)
        var nativeEditor: NSTextView?
        func editor() -> SelectionTextEditor {
            SelectionTextEditor(text: Binding(get: { text }, set: { text = $0 }),
                selection: Binding(get: { range }, set: { range = $0 }),
                editor: Binding(get: { nativeEditor }, set: { nativeEditor = $0 }))
        }
        let host = NSHostingView(rootView: editor())
        host.frame = CGRect(x: 0, y: 0, width: 620, height: 300)
        let window = NSWindow(contentRect: host.frame, styleMask: [.borderless], backing: .buffered, defer: false)
        window.isReleasedWhenClosed = false
        defer { window.close() }
        window.contentView = host
        host.layoutSubtreeIfNeeded()
        try await Task.sleep(for: .milliseconds(80))
        XCTAssertEqual(try XCTUnwrap(nativeEditor).string, "")
        let input = FormattingInput.resolve(external: { throw ClipActionFailure("unavailable") }, clipboard: { "current copied text 😀" })
        text = input.text
        host.rootView = editor()
        host.layoutSubtreeIfNeeded()
        try await Task.sleep(for: .milliseconds(80))
        XCTAssertEqual(nativeEditor?.string, "current copied text 😀")
        XCTAssertTrue(try XCTUnwrap(nativeEditor).isEditable)
        XCTAssertGreaterThan(try XCTUnwrap(nativeEditor?.enclosingScrollView).bounds.height, 0)
    }
    @MainActor func testCurrentClipboardHonorsProtectedTypesPauseAndBothSourceAndCurrentPrivacy() throws {
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        let suite = "NotchHub.FormattingInputTests." + UUID().uuidString
        let defaults = try XCTUnwrap(UserDefaults(suiteName: suite))
        defer { defaults.removePersistentDomain(forName: suite) }
        let root = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: root) }
        let preferences = HubPreferences(defaults: defaults)
        var foreground = "allowed.app"
        let store = HubStore(root: root, monitor: false, pasteboard: board, preferences: preferences, frontmostApp: { foreground })
        store.addText("stale history")
        XCTAssertThrowsError(try store.textForFormatting())
        board.setString("current only", forType: .string)
        XCTAssertEqual(try store.textForFormatting(), "current only")
        store.paused = true
        XCTAssertThrowsError(try store.textForFormatting())
        XCTAssertEqual(try store.textForFormatting(automatic: false), "current only")
        store.paused = false
        for type in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            board.clearContents(); board.setString("protected", forType: .string); board.setData(Data(), forType: .init(type))
            XCTAssertThrowsError(try store.textForFormatting())
        }
        board.clearContents(); board.setString("excluded", forType: .string)
        preferences.update { $0.excludedAppIDs = ["excluded.app"] }
        XCTAssertThrowsError(try store.textForFormatting(sourceApplicationID: "excluded.app"))
        foreground = "excluded.app"
        XCTAssertThrowsError(try store.textForFormatting(sourceApplicationID: "allowed.app"))
        XCTAssertEqual(try store.textForFormatting(sourceApplicationID: "allowed.app", automatic: false), "excluded")
        XCTAssertEqual(store.archive.clips.map(\.text), ["stale history"])
        preferences.setFeature(.privacy, enabled: false)
        XCTAssertEqual(try store.textForFormatting(sourceApplicationID: "allowed.app"), "excluded")
    }
}
